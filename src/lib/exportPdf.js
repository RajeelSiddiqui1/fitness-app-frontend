// Export Workout to CSV
export const exportWorkoutToCsv = (workout, userName) => {
  const headers = ['Field', 'Value'];
  const data = [
    ['Exercise Name', workout.exrciseName || ''],
    ['Status', workout.status || ''],
    ['Category', workout.category || ''],
    ['Sets', workout.sets || ''],
    ['Reps', workout.reps || ''],
    ['Weight (kg)', workout.weight || ''],
    ['Duration (min)', workout.duration || ''],
    ['Distance (km)', workout.distance || ''],
    ['Calories Burned', workout.caloriesBurned || ''],
    ['Date', workout.date ? new Date(workout.date).toLocaleDateString() : ''],
    ['Notes', workout.notes || ''],
    ['Generated By', userName],
    ['Generated Date', new Date().toLocaleDateString()]
  ];
  
  let csvContent = '\uFEFF'; // BOM for UTF-8
  csvContent += headers.join(',') + '\n';
  
  data.forEach(row => {
    const escapedRow = row.map(cell => {
      const cellStr = String(cell);
      if (cellStr.includes(',') || cellStr.includes('"') || cellStr.includes('\n')) {
        return `"${cellStr.replace(/"/g, '""')}"`;
      }
      return cellStr;
    });
    csvContent += escapedRow.join(',') + '\n';
  });
  
  downloadFile([csvContent], `workout-${workout.exrciseName || 'details'}-${new Date().toISOString().split('T')[0]}.csv`, 'text/csv;charset=utf-8');
};

