// Export Workout to PDF
export const exportWorkoutToPdf = (workout, userName) => {
  const doc = new jsPDF();
  
  const primaryColor = '#4F46E5';
  const textColor = '#1F2937';
  const mutedColor = '#6B7280';
  
  // Header
  doc.setFillColor(primaryColor);
  doc.rect(0, 0, 210, 40, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text('Workout Details', 105, 20, { align: 'center' });
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Generated by ${userName}`, 105, 30, { align: 'center' });
  
  doc.setTextColor(textColor);
  
  // Workout Name
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(workout.exrciseName || 'Workout', 20, 55);
  
  // Status badge
  const statusColor = workout.status === 'Completed' ? '#10B981' : 
                      workout.status === 'Missed' ? '#EF4444' : '#F59E0B';
  doc.setFillColor(statusColor);
  doc.roundedRect(20, 60, 35, 8, 2, 2, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(8);
  doc.text(workout.status, 37.5, 65.5, { align: 'center' });
  
  // Category
  doc.setTextColor(textColor);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Category: ${workout.category || 'N/A'}`, 20, 78);
  
  // Date
  if (workout.date) {
    doc.text(`Date: ${new Date(workout.date).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, 20, 86);
  }
  
  // Divider
  doc.setDrawColor(229, 231, 235);
  doc.line(20, 92, 190, 92);
  
  // Details section
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('Workout Details', 20, 102);
  
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  
  const details = [
    { label: 'Sets', value: workout.sets || 'N/A' },
    { label: 'Reps', value: workout.reps || 'N/A' },
    { label: 'Weight', value: `${workout.weight || 0} kg` },
    { label: 'Duration', value: workout.duration ? `${workout.duration} min` : 'N/A' },
    { label: 'Distance', value: workout.distance ? `${workout.distance} km` : 'N/A' },
    { label: 'Calories Burned', value: workout.caloriesBurned || 'N/A' },
  ];
  
  let yPos = 112;
  details.forEach((detail) => {
    doc.setTextColor(mutedColor);
    doc.text(detail.label, 20, yPos);
    doc.setTextColor(textColor);
    doc.setFont('helvetica', 'bold');
    doc.text(String(detail.value), 70, yPos);
    doc.setFont('helvetica', 'normal');
    yPos += 8;
  });
  
  // Notes section
  if (workout.notes) {
    yPos += 10;
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(textColor);
    doc.text('Notes', 20, yPos);
    
    yPos += 8;
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(mutedColor);
    
    const splitNotes = doc.splitTextToSize(workout.notes, 170);
    doc.text(splitNotes, 20, yPos);
  }
  
  // Footer
  const footerY = 280;
  doc.setDrawColor(229, 231, 235);
  doc.line(20, footerY, 190, footerY);
  doc.setFontSize(8);
  doc.setTextColor(mutedColor);
  doc.text('Generated from R-Fit Fitness App', 105, footerY + 8, { align: 'center' });
  doc.text(new Date().toLocaleDateString('en-US', { 
    year: 'numeric', 
    month: 'long', 
    day: 'numeric' 
  }), 105, footerY + 14, { align: 'center' });
  
  doc.save(`workout-${workout.exrciseName || 'details'}-${new Date().toISOString().split('T')[0]}.pdf`);
};

